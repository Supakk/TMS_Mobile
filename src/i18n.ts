export type Language = 'en' | 'th';
export type LanguageSetting = Language | 'auto';

export function deviceLanguage(): Language {
  return getLocales()[0]?.languageCode === 'th' ? 'th' : 'en';
}

let active: Language = deviceLanguage();

/** Called by the settings provider; the root layout remounts the screens when it changes. */
export function setActiveLanguage(language: Language) {
  active = language;
}

export function activeLanguage(): Language {
  return active;
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  let text = (active === 'th' ? th : en)[key];
  if (params) for (const [name, value] of Object.entries(params)) text = text.replace(`{${name}}`, String(value));
  return text;
}

/** Looks up a key built from an API code, such as statusIN_TRANSIT; falls back to the code itself. */
export function tCode(prefix: string, code: string): string {
  const key = `${prefix}${code}` as MessageKey;
  return key in en ? t(key) : code;
}
